"""Land-border lines and lakes for the Day 9 map (D139).

The map used to stroke whole country and province outlines, so every coast got
a solid line (1:50m) and a dashed one (1:10m) that never coincide. This writes
only the edges two units share on land, so the coast is drawn once, by a
hairline on the land fill, and lakes are cut out of the land.

Writes:
- `app/data/borders.json`: `country` lines (edges shared by two Natural Earth
  1:50m admin-0 countries, the same source as `world50.json`) and `lakes`
  (Natural Earth 1:50m lakes, larger than MIN_LAKE square degrees).
- `app/data/admin1/<ISO>_lines.json`: edges shared by two provinces of the same
  country (Natural Earth 1:10m admin-1, the same source as the province
  outlines), for each country in `day09.json` `admin1`.

Edges are found on the full-resolution shapes and simplified afterwards, so
neighbours share one line. Run after 14_app_export.py.

Usage: python 18_border_lines.py   (paths from MC26_DAY09_DIR)
"""
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

import pyogrio
import shapely
from shapely.ops import linemerge

DAY = Path(os.environ.get("MC26_DAY09_DIR") or sys.exit("Set MC26_DAY09_DIR to the Day 9 data folder (see README)."))
ADM0 = next((DAY / "raw-261108/ne/x_ne_50m_admin_0_countries").glob("*.shp"))
ADM1 = next((DAY / "raw-261108/ne/x_ne_10m_admin_1").glob("*.shp"))
LAKES = next((DAY / "raw-261109/ne/x_ne_50m_lakes").glob("*.shp"))
APP = Path(__file__).resolve().parents[1] / "app/data"
TOL0, TOL1 = 0.02, 0.01  # degrees, as for world50.json and the province outlines
MIN_LAKE = 0.05  # square degrees; keeps the large lakes, drops specks


def shared_edges(geoms):
    """Lines along which two of the given polygons touch, merged, in input order of pairs."""
    tree = shapely.STRtree(geoms)
    left, right = tree.query(geoms, predicate="intersects")
    parts = []
    for i, j in sorted(zip(left.tolist(), right.tolist(), strict=True)):
        if i >= j:
            continue
        x = shapely.intersection(geoms[i].boundary, geoms[j].boundary)
        parts += [g for g in getattr(x, "geoms", [x]) if g.geom_type in ("LineString", "MultiLineString")]
    if not parts:
        return []
    merged = linemerge(shapely.MultiLineString([p for g in parts for p in getattr(g, "geoms", [g])]))
    return list(getattr(merged, "geoms", [merged]))


def coords(line, tol):
    s = shapely.simplify(line, tol, preserve_topology=False)
    out = []
    for x, y in s.coords:
        q = [round(x, 3), round(y, 3)]
        if not out or q != out[-1]:
            out.append(q)
    return out if len(out) >= 2 else None


def ring_coords(poly, tol):
    s = shapely.simplify(poly, tol, preserve_topology=True)
    r = [[round(x, 3), round(y, 3)] for x, y in s.exterior.coords]
    return r if len(r) >= 4 else None


def check_between(lines, geoms, buf):
    """Every written line must sit between two units at its middle vertex: no coast or shore edges."""
    tree = shapely.STRtree(geoms)
    bad = [l for l in lines if len(tree.query(shapely.Point(l[len(l) // 2]).buffer(buf), predicate="intersects")) < 2]
    if bad:
        sys.exit(f"{len(bad)} line(s) do not lie between two units, e.g. {bad[0][:3]}")


def main():
    a0 = pyogrio.read_dataframe(ADM0, columns=["ISO_A2_EH"])
    a0 = a0[a0.geometry.notna()].reset_index(drop=True)
    g0 = list(shapely.make_valid(a0.geometry.values))
    country = [c for ln in shared_edges(g0) if (c := coords(ln, TOL0))]
    check_between(country, g0, 0.05)

    lk = pyogrio.read_dataframe(LAKES, columns=["name"])
    lakes = []
    for g in lk.geometry.values:
        for p in getattr(g, "geoms", [g]):
            if p.area >= MIN_LAKE and (r := ring_coords(p, TOL0)):
                lakes.append(r)
    lakes.sort(key=lambda r: (r[0][0], r[0][1]))

    (APP / "borders.json").write_text(json.dumps({
        "note": "Natural Earth 1:50m (public domain): land borders shared by two countries, and lakes. "
                "Generated by 18_border_lines.py; do not edit.",
        "country": country, "lakes": lakes}, separators=(",", ":")))

    isos = set(json.loads((APP / "day09.json").read_text())["admin1"])
    a1 = pyogrio.read_dataframe(ADM1, columns=["iso_a2"])
    by = defaultdict(list)
    for iso, g in zip(a1["iso_a2"], a1.geometry.values, strict=True):
        if iso in isos and g is not None:
            by[iso].append(shapely.make_valid(g))
    n = 0
    for iso in sorted(by):
        lines = [c for ln in shared_edges(by[iso]) if (c := coords(ln, TOL1))]
        check_between(lines, by[iso], 0.03)
        (APP / "admin1" / f"{iso}_lines.json").write_text(json.dumps(lines, separators=(",", ":")))
        n += len(lines)
    print(f"country lines {len(country)}, lakes {len(lakes)}, province lines {n} in {len(by)} countries")


if __name__ == "__main__":
    main()
